KINDS = {
    "alarm": "Alarms", "communication": "Communications", "chat": "Chats",
    "log": "Operator logs", "workforce": "Workforce", "outage": "Outages",
    "switching": "Switching", "field": "Field reports", "scada": "SCADA imports",
    "voice": "Voice", "governance": "Governance", "library": "Library",
    "system": "Systems", "other": "Other",
}
CATEGORY = """CASE
 WHEN event_type LIKE '%.note.added' AND json_valid(payload) THEN COALESCE(json_extract(payload,'$.category'),'other')
 WHEN aggregate_type='price_alert' OR event_type LIKE 'alarm.%'
   OR event_type LIKE 'workforce.%help%' OR event_type LIKE 'workforce.%overdue%' THEN 'alarm'
 WHEN aggregate_type='communication' OR event_type LIKE 'communications.%' THEN 'communication'
 WHEN aggregate_type='conversation' OR event_type LIKE 'chat.%' THEN 'chat'
 WHEN source='logbook' THEN 'log'
 WHEN source='workforce' THEN 'workforce'
 WHEN source IN ('outage','outages') THEN 'outage'
 WHEN source='switching' THEN 'switching'
 WHEN source='voice' THEN 'voice'
 WHEN source='scada' THEN 'scada'
 WHEN source='field_operations' THEN 'field'
 WHEN source='governance' THEN 'governance'
 WHEN source='library' THEN 'library'
 WHEN aggregate_type='system' OR source='system' THEN 'system' ELSE 'other' END"""
SORT = "COALESCE(julianday(occurred_at),julianday(recorded_at),0)"
# Payloads are generated by our writers, but tolerate legacy malformed JSON.
PAYLOAD = "CASE WHEN json_valid(payload) THEN payload ELSE '{}' END"
STATE = f"COALESCE(json_extract({PAYLOAD},'$.newState'),json_extract({PAYLOAD},'$.newStatus'),json_extract({PAYLOAD},'$.status'),'')"
SITE = f"COALESCE(json_extract({PAYLOAD},'$.site'),json_extract({PAYLOAD},'$.siteCode'),'')"
SITE_ID = f"COALESCE(json_extract({PAYLOAD},'$.siteId'),'')"


def _list(params, name):
    value = params.get(name, [])
    return value if isinstance(value, list) else [value]


def _one(params, name, default=""):
    return str((_list(params, name) or [default])[0])


def _stamp(value):
    date = datetime.fromisoformat(value.replace("Z", "+00:00"))
    if date.tzinfo is None:
        raise ValueError("Date filters require a timezone")
    return date.isoformat()


def _decode(value):
    try:
        if len(value) > 2000:
            raise ValueError()
        item = json.loads(base64.urlsafe_b64decode(value.encode()).decode())
        if not isinstance(item, dict) or not isinstance(item.get("snapshot"), int) or item["snapshot"] < 0:
            raise ValueError()
        if not isinstance(item.get("seq"), int) or item["seq"] < 0 or not math.isfinite(float(item.get("time"))):
            raise ValueError()
        return item
    except (ValueError, TypeError, KeyError, UnicodeError) as exc:
        raise ValueError("Invalid history cursor") from exc


def _encode(value):
    return base64.urlsafe_b64encode(json.dumps(value,separators=(",", ":")).encode()).decode()


def _record(row):
    item = events.record(row)
    item.update(category=row["category"], status=row["event_status"], site=row["event_site"])
    return item


def _query(connection, params, *, relation=None):
    """Snapshot keyset pagination; incoming events cannot move page boundaries."""
    clauses, values = [], []
    for name, column in [("type",CATEGORY),("source","source"),("severity","severity"),("status",STATE)]:
        selected = [str(v) for v in _list(params,name) if v]
        if len(selected) > 30:
            raise ValueError("Too many filter values")
        if selected:
            clauses.append(f"({column}) IN ({','.join('?' for _ in selected)})")
            values.extend(selected)
    for name, column in [("site",SITE),("actor","actor_id"),("equipment",f"COALESCE(json_extract({PAYLOAD},'$.equipment'),json_extract({PAYLOAD},'$.node'),'')")]:
        value = _one(params,name).strip()
        if value:
            clauses.append(f"({column}) LIKE ? ESCAPE '\\'")
            values.append('%'+value.replace('\\','\\\\').replace('%','\\%').replace('_','\\_')+'%')
    q = _one(params,"q").strip()
    if len(q)>500:
        raise ValueError("Search exceeds 500 characters")
    if q:
        clauses.append("(summary LIKE ? ESCAPE '\\' OR payload LIKE ? ESCAPE '\\' OR actor_id LIKE ? ESCAPE '\\' OR event_id=?)")
        pattern='%'+q.replace('\\','\\\\').replace('%','\\%').replace('_','\\_')+'%'
        values.extend([pattern,pattern,pattern,q])
    for name, operator in [("from",">="),("to","<=")]:
        value = _one(params,name)
        if value:
            clauses.append(f"({SORT}) {operator} julianday(?)")
            values.append(_stamp(value))
    if relation:
        clauses.append('('+relation[0]+')');values.extend(relation[1])
    try:
        limit=max(1,min(100,int(_one(params,"limit","50"))))
    except ValueError as exc:
        raise ValueError("Invalid page size") from exc
    signature=hashlib.sha256(json.dumps([clauses,values],sort_keys=True).encode()).hexdigest()
    raw_cursor=_one(params,"cursor")
    cursor=_decode(raw_cursor) if raw_cursor else None
    if cursor and cursor.get("filter")!=signature:
        raise ValueError("Cursor does not match the selected filters")
    snapshot=cursor["snapshot"] if cursor else connection.execute("SELECT COALESCE(MAX(seq),0) FROM audit_events").fetchone()[0]
    clauses.append("seq<=?");values.append(snapshot)
    where=" AND ".join(clauses) or "1=1"
    total=connection.execute("SELECT count(*) FROM audit_events WHERE "+where,values).fetchone()[0]
    if cursor:
        clauses.append(f"(({SORT})<? OR (({SORT})=? AND seq<?))")
        values.extend([cursor["time"],cursor["time"],cursor["seq"]])
    rows=connection.execute(f"SELECT *, ({CATEGORY}) AS category, ({STATE}) AS event_status, ({SITE}) AS event_site, ({SORT}) AS sort_time FROM audit_events WHERE {' AND '.join(clauses)} ORDER BY ({SORT}) DESC,seq DESC LIMIT ?",[*values,limit+1]).fetchall()
    more=len(rows)>limit;rows=rows[:limit]
    next_cursor=_encode({"time":rows[-1]["sort_time"],"seq":rows[-1]["seq"],"snapshot":snapshot,"filter":signature}) if more else None
    return {"items":[_record(row) for row in rows],"total":total,"nextCursor":next_cursor,
            "snapshot":snapshot,"fetchedAt":datetime.now(timezone.utc).isoformat()}


def register(params):
    with store._session() as connection:
        return _query(connection,params)


def detail(event_id, params):
    with store._session() as connection:
        row=connection.execute(f"SELECT *, ({CATEGORY}) AS category, ({STATE}) AS event_status, ({SITE}) AS event_site FROM audit_events WHERE event_id=?",(event_id,)).fetchone()
        if row is None:
            raise LookupError("Event not found")
        # Object identity, not a timestamp or title, defines an event's lifecycle.
        relation=("aggregate_type=? AND aggregate_id=?",[row["aggregate_type"],row["aggregate_id"]])
        if row["aggregate_type"]=="communication" and row["correlation_id"]:
            relation=("aggregate_type='communication' AND source=? AND correlation_id=?",[row["source"],row["correlation_id"]])
        elif row["aggregate_type"]=="system" and row["aggregate_id"]=="system":
            relation=("event_id=? OR causation_id=?",[event_id,event_id])
        section=_one(params,"section","history")
        if section not in {"history","occurrences","related"}:
            raise ValueError("Unknown event history section")
        # Repeated transitions are only comparable within the same source,
        # object and recorded state. Notes never inflate recurrence counts.
        recurrence=(f"({relation[0]}) AND source=? AND event_type=? AND ({STATE})=? AND event_type NOT LIKE '%.note.added'",
                    [*relation[1],row['source'],row['event_type'],row['event_status']])
        links=["causation_id=?", "event_id=?"]
        linked_values=[event_id,row['causation_id'] or '']
        if row['correlation_id']:
            links.append("(source=? AND correlation_id=?)")
            linked_values.extend([row['source'],row['correlation_id']])
        related=("event_id!=? AND ("+' OR '.join(links)+")",[event_id,*linked_values])
        selected={"history":relation,"occurrences":recurrence,"related":related}[section]
        result=_query(connection,params,relation=selected)
        stats=connection.execute(f"SELECT count(*) AS total, MIN({SORT}) AS first, MAX({SORT}) AS last, SUM(CASE WHEN ({SORT})<? THEN 1 ELSE 0 END) AS prior FROM audit_events WHERE ({recurrence[0]}) AND seq<=?",
            [connection.execute('SELECT '+SORT+' FROM audit_events WHERE event_id=?',(event_id,)).fetchone()[0],*recurrence[1],result['snapshot']]).fetchone()
        return {"event":_record(row),"history":result,"historyOrder":"newest_first", "section":section,
                "recurrence":{"total":stats['total'],"prior":stats['prior'] or 0,
                    "firstOccurredAt":connection.execute('SELECT strftime(\'%Y-%m-%dT%H:%M:%fZ\',?)',(stats['first'],)).fetchone()[0],
                    "lastOccurredAt":connection.execute('SELECT strftime(\'%Y-%m-%dT%H:%M:%fZ\',?)',(stats['last'],)).fetchone()[0],
                    "basis":"Same source, object or provider thread, event type and recorded state; operator notes excluded."},
                "relationshipBasis":"Recorded object lifecycle" if section=='history' else "Explicit cause or same source correlation ID" if section=='related' else "Matching recorded transitions"}


def add_note(event_id, text, actor, request_id):
    text=str(text or "").strip();request_id=str(request_id or "")
    if not text or len(text)>8000:
        raise ValueError("Enter a note of 1–8000 characters")
    if not request_id or len(request_id)>100:
        raise ValueError("A note request ID is required")
    identity='note_'+hashlib.sha256(json.dumps([event_id,actor,request_id]).encode()).hexdigest()
    with store._LOCK,store._session() as connection:
        parent=connection.execute(f"SELECT *, ({CATEGORY}) AS category FROM audit_events WHERE event_id=?",(event_id,)).fetchone()
        if parent is None:
            raise LookupError("Event not found")
        prior=connection.execute("SELECT payload FROM audit_events WHERE event_id=?",(identity,)).fetchone()
        if prior:
            if json.loads(prior[0]).get('details')!=text:
                raise ValueError("This note request ID was already used")
            return {"eventId":identity,"href":events.report_href(identity),"duplicate":True}
        try:
            parent_payload=json.loads(parent['payload'])
        except (ValueError,TypeError):
            parent_payload={}
        context={key:parent_payload[key] for key in ('site','siteId','siteCode','equipment','node','threadId','sourceLabel') if isinstance(parent_payload,dict) and key in parent_payload}
        # Inherit category identity but not lifecycle state: a note never acknowledges an alarm.
        events.append_event(connection,event_id=identity,event_type=parent["event_type"].split('.')[0]+'.note.added',
            occurred_at=datetime.now(timezone.utc).isoformat(),actor_id=actor,
            aggregate_type=parent["aggregate_type"],aggregate_id=parent["aggregate_id"],
            source=parent["source"],summary="Operator note",payload={**context,"details":text,"parentEventId":event_id,"recordKind":"note","category":parent["category"]},
            correlation_id=parent["correlation_id"],causation_id=event_id)
    return {"eventId":identity,"href":events.report_href(identity),"duplicate":False}


def record_chat(text, actor, conversation_id=None, *, outcome="question", causation_id=None):
    conversation_id=conversation_id or events.new_id('conversation')
    with store._LOCK,store._session() as connection:
        event_id=events.append_event(connection,event_type='chat.'+outcome,
            occurred_at=datetime.now(timezone.utc).isoformat(),actor_id=actor,
            aggregate_type="conversation",aggregate_id=conversation_id,source="assistant",
            summary={"question":"Operator question","answer":"AI response","failed":"AI request failed"}.get(outcome,outcome),
            severity="warning" if outcome=="failed" else "info",payload={"details":str(text),"status":outcome,"assistiveOnly":True},
            correlation_id=conversation_id,causation_id=causation_id)
    return conversation_id,event_id


def sources():
    with store._session() as connection:
        rows=connection.execute("SELECT source,count(*) AS count,MAX(recorded_at) AS last FROM audit_events GROUP BY source ORDER BY source").fetchall()
        statuses=[r[0] for r in connection.execute(f"SELECT DISTINCT ({STATE}) FROM audit_events WHERE ({STATE})!='' ORDER BY 1 LIMIT 100")]
    observed={row['source']:row for row in rows}
    names={"logbook":"Operator logs","workforce":"Workforce","market":"IESO / APIROQ alarms",
           "outage":"Outages","outages":"Outages",
           "switching":"Switching","field_operations":"Field operations","voice":"Voice recordings","scada":"SCADA imports",
           "governance":"Governance","assistant":"Operations AI","library":"Device library",
           "outlook":"Outlook","teams":"Teams"}
    for name in observed:names.setdefault(name,name)
    items=[]
    for name,label in names.items():
        row=observed.get(name)
        state="Setup pending" if name in {"outlook","teams"} else "Recording supported"
        items.append({"id":name,"label":label,"state":state,"count":row['count'] if row else 0,
                      "lastRecordedAt":row['last'] if row else None})
    for name,label in [('weather','Weather observations'),('dispatch','Dispatch telemetry')]:
        if name not in names:
            items.append({'id':name,'label':label,'state':'Telemetry is not archived in the event ledger',
                          'count':0,'lastRecordedAt':None})
    return {"sources":items,"types":[{"id":k,"label":v} for k,v in KINDS.items()],"statuses":statuses,
            "note":"Recorded history is not proof of a live connection. Outlook and Teams collection is not enabled."}
