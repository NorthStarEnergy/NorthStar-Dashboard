  await page.locator('#nsAssetEditor [name="root"]').selectOption('fixed:dispatch');
  await page.locator('#nsAssetEditor [name="moduleWidth"]').fill('180');
  await page.locator('#nsAssetEditor [name="moduleHeight"]').fill('250');
