const assert=require('node:assert/strict');
const {spawn}=require('node:child_process');
const {once}=require('node:events');
const {createInterface}=require('node:readline');
const fs=require('node:fs');
const path=require('node:path');
const {chromium}=require('playwright');

async function check() {
  const root=path.resolve(__dirname,'..');
  const server=spawn('python',['-u','tests/uwpc-desk-fixture.py'],{cwd:root,windowsHide:true,env:{...process.env,OUTAGE_MANAGER_FIXTURE:'1'},stdio:['ignore','pipe','inherit']});
  let browser;
  try {
    const lines=createInterface({input:server.stdout});
    const port=await Promise.race([once(lines,'line').then(([l])=>JSON.parse(l).port),once(server,'exit').then(()=>{throw Error('Fixture exited');})]);
    const origin='http://127.0.0.1:'+port;
    browser=await chromium.launch({channel:'msedge',headless:true});
    const context=await browser.newContext({viewport:{width:1366,height:768}});
    const page=await context.newPage();
    await page.route('**/api/**',route=>{
      const pathname=new URL(route.request().url()).pathname;
      if (/^\/api\/(auth|uwpc|switching|outages|sites)/.test(pathname)) return route.continue();
      return route.fulfill({status:503,contentType:'application/json',body:'{}'});
    });
    assert.equal((await context.request.get(origin+'/api/uwpc/requests/manager/register')).status(),401);
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(origin+'/outage-manager.html');
    assert.equal(await page.locator('input[type=password]').count(),1);
    await page.locator('#username').fill('fixture_author');
    await page.locator('#password').fill('fixture-only-password');
    await page.locator('button[type=submit]').click();
    await page.locator('tbody').getByRole('link',{name:'Unit 2 stator inspection'}).waitFor();
    for(const shell of ['/northstar-v1.html?buildView=v1','/northstar-clean.html?buildView=v3']){
      await page.goto(origin+shell);
      await page.waitForFunction(()=>window.NorthstarModules?.registry.has('outages:uwpc'));
      await page.locator('#sideNav [data-tab=outages]').click();
      await page.locator('#sideNav a[href="/outage-manager.html"]:visible').first().click();
      await page.locator('tbody').getByRole('link',{name:'Unit 2 stator inspection'}).waitFor();
    }
    assert.equal(await page.locator('tbody tr').count(),3);
    const out=path.join(root,'outputs','outage-manager-qa');fs.mkdirSync(out,{recursive:true});
    const folder=page.locator('#outageTree .package-folder');
    async function expectFolder(title){
      await folder.locator('summary').filter({hasText:title}).waitFor({state:'attached'});
      assert.equal(await folder.count(),1);
    }
    const first='Unit 2 stator inspection', second='Feeder protection review';
    await expectFolder(first);
    const rowTop=await page.locator('tbody tr').first().evaluate(el=>Math.round(el.getBoundingClientRect().top));
    assert.ok(rowTop<120,'The register should open directly on the rows');
    console.log('First register row at '+rowTop+' px on a 1366 × 768 viewport.');
    await page.locator('tbody').getByRole('link',{name:second}).click();
    await expectFolder(second);
    await page.goBack();
    await expectFolder(second);
    await page.reload();
    await expectFolder(second);
    await page.getByRole('link',{name:'Outages',exact:true}).click();
    await expectFolder(second);
    await page.locator('tbody').getByRole('link',{name:first}).click();
    await expectFolder(first);
    await page.getByRole('link',{name:'Outages',exact:true}).click();
    await expectFolder(first);
    assert.deepEqual(await page.locator('#packageNav > a').allTextContents(),['Home','New','Outages','UWPC library','My reviews']);
    await page.screenshot({path:path.join(out,'home.png')});
    await page.getByRole('button',{name:/^Past/}).click();
    await page.locator('tbody').getByRole('link',{name:'Completed valve inspection'}).waitFor();
    await expectFolder(first);
    await page.getByRole('button',{name:/^Upcoming/}).click();
    await page.getByRole('searchbox',{name:'Search outages'}).fill('feeder');
    await page.waitForFunction(()=>document.querySelectorAll('tbody tr').length===1 && document.querySelector('tbody')?.textContent.includes('Feeder protection'));
    await page.getByRole('link',{name:'New',exact:true}).click();
    assert.ok(await page.getByRole('button',{name:'Create outage'}).evaluate(el=>el.getBoundingClientRect().bottom<innerHeight));
    await page.screenshot({path:path.join(out,'new.png')});
    await page.getByLabel('Outage name').fill('West bay inspection');
    await page.getByLabel('Primary site').fill('Norman');
    await page.getByLabel('Equipment',{exact:true}).fill('West bay');
    await page.getByLabel('Start',{exact:true}).fill('2030-09-18T07:00');
    await page.getByLabel('End',{exact:true}).fill('2030-09-18T17:00');
    await page.getByLabel('Work scope').fill('Review the west bay references.');
    await page.getByLabel('Review trigger').selectOption('manager designation');
    await page.getByLabel('SSC outage manager',{exact:true}).selectOption('fixture_operator');
    await page.getByLabel('Local outage manager',{exact:true}).selectOption('fixture_area');
    await page.getByRole('button',{name:'Create outage'}).click();
    await page.getByRole('heading',{name:'West bay inspection'}).waitFor();
    const tree=page.locator('.package-folder[open]').filter({has:page.locator('a[aria-current=page]')});
    const progress=page.getByRole('navigation',{name:'Outage process'});
    assert.match(await progress.locator('[aria-current=step]').innerText(),/Preparation/);
    assert.match(await page.locator('.coordination').innerText(),/fixture_operator/);
    await page.screenshot({path:path.join(out,'package-overview.png')});
    await tree.getByRole('link',{name:'Request',exact:true}).click();
    await page.getByRole('heading',{name:'Request',exact:true}).waitFor();
    assert.ok(await page.getByText('West bay',{exact:true}).isVisible());
    await page.reload();
    await progress.getByRole('link',{name:'Team review'}).click();
    await page.locator('#outageRouting').waitFor();
    assert.equal(await page.locator('#outageRouting [name=sscLead]').inputValue(),'fixture_operator');
    assert.equal(await page.locator('#uwpcRequestForm').count(),0);
    await tree.getByRole('link',{name:'Drawings & documents'}).click();
    await page.locator('#uwpcSourceUpload').waitFor();
    assert.equal(await page.locator('#outageRouting').count(),0);
    await tree.getByRole('link',{name:'Switching log'}).click();
    await page.getByText('The switching log has not opened.').waitFor();
    await page.goBack();
    await page.locator('#uwpcSourceUpload').waitFor();
    await tree.getByRole('link',{name:'Forms',exact:true}).click();
    await page.locator('#uwpcRequestForm [name=title]').waitFor();
    assert.equal(await page.locator('#uwpcRequestForm [name=title]').inputValue(),'West bay inspection');
    assert.equal(await page.getByRole('link',{name:'Open practice outage'}).count(),0);
    await page.getByRole('link',{name:'My reviews'}).click();
    await page.getByText('You have no outstanding reviews.').waitFor();
    if(process.env.OUTAGE_MANAGER_FIXTURE_BOOK){
      await page.getByRole('link',{name:'UWPC library',exact:true}).click();
      const source=page.locator('.reader').getByRole('link',{name:'Open source PDF'});
      await source.waitFor();
      assert.equal(await source.getAttribute('href'),'/api/uwpc/requests/manager/library/book');
      assert.ok(await page.locator('#readerHost').evaluate(el=>el.getBoundingClientRect().top<170));
      await page.setViewportSize({width:390,height:844});
      await page.reload();
      await source.waitFor();
      const mobileReaderTop=await page.locator('#readerHost').evaluate(el=>Math.round(el.getBoundingClientRect().top));
      await page.screenshot({path:path.join(out,'mobile-manual.png')});
      assert.ok(mobileReaderTop<260,'Mobile reader starts at '+mobileReaderTop+' px');
      await page.setViewportSize({width:1366,height:768});
      await page.getByRole('searchbox',{name:'Search the manual'}).fill('supporting guarantee');
      await page.locator('#contents a strong').first().waitFor();
      await page.getByLabel('Reading format').selectOption('text');
      await page.locator('#contents a').first().click();
      await page.locator('.pageText p').waitFor();
      assert.ok((await page.locator('.pageText p').innerText()).length>20);
      await page.getByRole('button',{name:'Forms & tags'}).click();
      const pc2=page.locator('.formref').filter({has:page.getByText('PC2',{exact:true})});
      const link=await pc2.getByRole('link',{name:'PDF',exact:true}).getAttribute('href');
      assert.equal(await page.evaluate(async u=>{const r=await fetch(u);return (await r.arrayBuffer()).byteLength>1000 && r.headers.get('content-type')==='application/pdf';},link),true);
      await page.getByRole('button',{name:'Practice questions'}).click();
      await page.getByText('How many devices can a PC10A work permit guarantee?').click();
      assert.ok(await page.locator('#main .questions details[open] a').isVisible());
    }
    await page.setViewportSize({width:390,height:844});
    await page.getByRole('button',{name:'Menu',exact:true}).click();
    await page.getByRole('link',{name:'Outages',exact:true}).click();
    await page.locator('tbody').getByRole('link',{name:'West bay inspection'}).waitFor();
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.locator('tbody').getByRole('link',{name:'West bay inspection'}).click();
    await page.getByRole('heading',{name:'West bay inspection'}).waitFor();
    await page.getByRole('button',{name:'Menu',exact:true}).click();
    await tree.getByRole('link',{name:'Request',exact:true}).click();
    await page.getByRole('heading',{name:'Request',exact:true}).waitFor();
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.setViewportSize({width:1440,height:900});
    await tree.getByRole('link',{name:'Forms',exact:true}).click();
    const form=page.locator('#uwpcRequestForm');
    await form.locator('[name=diagramRevision]').fill('R1');
    await form.locator('[data-step-field=device]').first().fill('Fixture device');
    await form.locator('[data-step-field=operation]').first().fill('Fixture step');
    await form.getByRole('button',{name:'Save changes'}).click();
    await page.getByText('Form saved.',{exact:false}).first().waitFor();
    await tree.getByRole('link',{name:'Drawings & documents'}).click();
    await page.locator('#uwpcSourceUpload').setInputFiles({name:'drawing.txt',mimeType:'text/plain',buffer:Buffer.from('Fixture')});
    await page.getByRole('button',{name:'Attach',exact:true}).click();
    await page.getByText('Source saved with this package.').waitFor();
    await tree.getByRole('link',{name:'Approvals'}).click();
    const route=page.locator('#outageRouting');
    await route.locator('[name=due]').fill('2030-09-17T10:00');
    await route.locator('[name=checker]').selectOption('fixture_operator');
    await route.locator('[name=area]').selectOption('fixture_area');
    await route.locator('[name=scheduled][value=fixture_operator]').check();
    await route.locator('[data-field-site=Norman]').selectOption('fixture_north');
    await route.getByText('Final-copy viewers',{exact:true}).click();
    await route.locator('[name=copyTo][value=Ryan]').check();
    await route.locator('[name=confirmed]').check();
    await route.getByRole('button').click();
    await page.getByText('Outage package review · Awaiting signatures',{exact:true}).waitFor();
    const approvals=page.url();
    async function asUser(name,url){
      const response=await context.request.post(origin+'/api/auth/login',{data:{username:name,password:'fixture-only-password'}});
      assert.equal(response.status(),200);
      if(page.url()===url)await page.reload();else await page.goto(url);
    }
    for(const name of ['fixture_operator','fixture_area','fixture_north','fixture_operator']){
      await asUser(name,approvals);
      const task=page.locator('[data-task]').filter({has:page.locator('[data-action=review-sign]')}).first();
      await task.locator('[name=confirmed]').check();
      await task.locator('[data-action=review-sign]').click();
      await page.waitForFunction(()=>!document.querySelector('#uwpcDesk').hasAttribute('aria-busy'));
    }
    await progress.locator('[aria-current=step]').filter({hasText:'Final copy'}).waitFor();
    await asUser('Ryan',origin+'/outage-manager.html#inbox');
    await page.locator('#reviews a').filter({hasText:'Final copy distributed'}).click();
    await page.getByRole('link',{name:'Download final copy'}).waitFor();
    await page.getByRole('textbox',{name:'Concern',exact:true}).fill('Confirm crew arrival');
    await page.getByRole('button',{name:'Send to outage managers'}).click();
    await page.getByText('Concern sent to the outage managers.').waitFor();
    await asUser('fixture_area',origin+'/outage-manager.html#inbox');
    await page.locator('#reviews a').filter({hasText:'Final copy flagged'}).click();
    await page.getByLabel('Resolution',{exact:true}).fill('Crew time confirmed');
    await page.getByRole('button',{name:'Resolve concern'}).click();
    await page.getByText('Resolution recorded.').waitFor();
    await asUser('fixture_relief',origin+'/outage-manager.html#outages');
    await expectFolder(first);
    await page.evaluate(()=>localStorage.setItem('northstar.outageManager.last.fixture_relief','missing-outage'));
    await page.reload();
    await expectFolder(first);
    await asUser('fixture_author',origin+'/outage-manager.html#outages');
    await expectFolder('West bay inspection');
    assert.deepEqual(errors,[]);
    console.log('Outage Manager register, creation, package, inbox, library and mobile checks passed.');
  }finally{if(browser)await browser.close();server.kill();}
}
check().catch(e=>{console.error(e);process.exitCode=1;});
