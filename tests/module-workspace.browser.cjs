/* Run with NODE_PATH pointing at a Playwright installation; no live API writes. */
const {chromium}=require('playwright');
const http=require('node:http'),fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
(async()=>{
 const server=http.createServer((req,res)=>{
   const pathname=decodeURIComponent(new URL(req.url,'http://localhost').pathname);
   const target=path.resolve(root,'.'+pathname);
   if(!target.startsWith(root+path.sep)||!['.html','.js','.css','.svg','.png','.ico'].includes(path.extname(target))){res.writeHead(404);res.end();return;}
   fs.readFile(target,(err,data)=>{res.writeHead(err?404:200,{'Content-Type':{'.html':'text/html','.js':'text/javascript','.css':'text/css','.svg':'image/svg+xml'}[path.extname(target)]||'application/octet-stream'});res.end(err?'':data);});
 });
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage({viewport:{width:1500,height:980}}),errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 await page.route('**/api/**',route=>{
   const pathname=new URL(route.request().url()).pathname;
   const data=pathname==='/api/auth/session'?{required:false}:pathname==='/api/weather'?{stations:[]}:pathname==='/api/market-prices'?{updated:'2026-09-15T00:00:00Z',nodes:{APIROQ:{rt:42,da:37,history:[],operations:{rtTransfer:12,dayAhead:10}}},ontario:{demand:15000,forecastDemand:15500}}:{};
   return route.fulfill({status:['/api/auth/session','/api/weather','/api/market-prices'].includes(pathname)?200:503,contentType:'application/json',body:JSON.stringify(data)});
 });
 try{
   await page.goto(`http://127.0.0.1:${server.address().port}/northstar-clean.html`);
   await page.waitForFunction(()=>window.NorthstarModules?.registry.size>10);
   await page.click('#sideNav [data-tab="weather"]');
   await page.waitForSelector('.ns-module-tree button');
   assert.equal(await page.locator('.ns-module-window:visible').count(),1);
   assert.equal(await page.locator('#weatherGridFull > .weather-card:visible').count(),1);
   const ids=await page.evaluate(()=>[...NorthstarModules.registry.values()].filter(m=>m.section==='weather').map(m=>m.id));
   assert.ok(ids.length>1);
   await page.locator('.ns-module-tree button').nth(1).click();
   assert.equal(await page.locator('.ns-tab').count(),2);
   assert.equal(await page.locator('.ns-module-window:visible').count(),1);
   await page.click('[data-ns-action="landing"]');
   await page.click('[data-ns-action="float"]');
   assert.equal(await page.locator('.ns-module-window:visible').count(),2);
   assert.equal(await page.locator('#weatherGridFull > .weather-card:visible').count(),2);
   const target=page.locator('.ns-module-window:visible').last();
   const before=await target.boundingBox();
   const handle=target.locator('.ns-window-handle[data-corner="nw"]');
   await handle.focus();await page.keyboard.press('ArrowRight');await page.keyboard.press('ArrowDown');
   const after=await target.boundingBox();assert.equal(Math.round(after.x-before.x),5);assert.equal(Math.round(before.width-after.width),5);
   await page.click('[data-ns-action="edit"]');
   await page.fill('#nsModuleEditor [name="moduleName"]','Test station module');
   await page.fill('#nsModuleEditor [name="notes"]','Full page test notes');
   await page.click('#nsModuleEditor button[type="submit"]');
   assert.ok((await page.locator('.ns-module-tree').innerText()).includes('Test station module'));
   await page.evaluate(id=>NorthstarModules.edit(id,'compact'),ids[1]);
   await page.fill('#nsModuleEditor [name="notes"]','Compact test notes');
   await page.click('#nsModuleEditor button[type="submit"]');
   await page.reload();await page.waitForFunction(()=>!!window.NorthstarModules);
   await page.click('#sideNav [data-tab="weather"]');
   assert.equal(await page.evaluate(()=>NorthstarModules.state.sections.weather.active),ids[1]);
   assert.equal(await page.evaluate(id=>NorthstarModules.state.modules[id].full.notes,ids[1]),'Full page test notes');
   assert.equal(await page.evaluate(id=>NorthstarModules.state.modules[id].compact.notes,ids[1]),'Compact test notes');
   await page.click('#sideNav [data-tab="outages"]');
   assert.equal(await page.locator('.ns-module-window:visible').count(),1);
   await page.locator('[data-open-module="outages:switching-intake"]').click();
   assert.equal(await page.locator('#wpPackageName:visible').count(),1);
   assert.equal(await page.locator('.ns-module-window:visible').count(),1);
   await page.click('#sideNav [data-tab="markets"]');
   assert.equal(await page.locator('#marketDetail:visible').count(),1);
   await page.evaluate(()=>openNode('APIROQ'));
   assert.equal(await page.locator('#nsMarket-APIROQ:visible').count(),1);
   assert.equal(await page.locator('#marketDetail:visible').count(),0);
   assert.ok((await page.locator('#nsMarket-APIROQ').innerText()).includes('$42.00'));
   assert.equal(await page.locator('#nsMarket-APIROQ [data-market-control="alertLow"]').count(),1);
   await page.click('#sideNav [data-tab="tools"]');
   await page.locator('[data-open-module="tools:device-library"]').click();
   assert.equal(await page.locator('#deviceLibrary:visible').count(),1);
   assert.equal(await page.locator('.ns-module-window:visible').count(),1);
   await page.click('#sideNav [data-tab="modules"]');
   await page.fill('#nsNewName','Custom test');await page.click('#nsCreateModule');
   await page.fill('#nsModuleEditor [name="notes"]','Custom content');await page.click('#nsModuleEditor button[type="submit"]');
   const customId=await page.evaluate(()=>[...NorthstarModules.registry.keys()].find(id=>id.startsWith('custom:')));
   await page.evaluate(id=>NorthstarModules.edit(id),customId);
   await page.fill('#nsModuleEditor [name="notes"]','Full draft retained');
   await page.selectOption('#nsModuleEditor [name="variant"]','compact');
   await page.fill('#nsModuleEditor [name="notes"]','Overview draft retained');
   await page.check('#nsModuleEditor [name="customOnly"]');
   await page.click('#nsModuleEditor button[type="submit"]');
   assert.equal(await page.evaluate(id=>NorthstarModules.state.modules[id].full.notes,customId),'Full draft retained');
   await page.click('#sideNav [data-tab="weather"]');
   await page.click('[data-ns-action="float"]');
   assert.equal(await page.locator('#weatherGridFull > .weather-card:visible').count(),1);
   await page.locator('.ns-module-window:visible .ns-window-handle[data-corner="se"]').focus();
   await page.keyboard.press('ArrowLeft');
   assert.equal(await page.evaluate(()=>NorthstarModules.state.sections.weather.floating),true,'Resizing a full page restores module windows');
   await page.click('#sideNav [data-tab="overview"]');
   await page.click('.layout-edit-toggle');
   const tile=page.locator('#weatherStrip > .weather-card').first();
   const geometry=await tile.boundingBox();
   await tile.locator('.canvas-resize-handle[data-corner="nw"]').focus();await page.keyboard.press('ArrowRight');
   const resized=await tile.boundingBox();assert.equal(Math.round(geometry.width-resized.width),5);
   await page.click('.layout-save');
   const saved=await page.evaluate(()=>localStorage.getItem('northstarCanvasLayoutV1'));
   await page.reload();await page.waitForFunction(()=>!!window.NorthstarModules);
   assert.equal(await page.evaluate(()=>localStorage.getItem('northstarCanvasLayoutV1')),saved,'Overview geometry survives reload');
   await page.click('#sideNav [data-tab="weather"]');
   fs.mkdirSync(path.join(root,'outputs'),{recursive:true});
   await page.screenshot({path:path.join(root,'outputs','module-workspace-browser.png'),fullPage:false});
   console.log('Browser errors:',errors);
   assert.equal(errors.length,0);
   console.log('Module browser scenarios passed.');
 }finally{await browser.close();server.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
