def templates() -> list[dict[str, Any]]:
    return [deepcopy(row) for row in TEMPLATES]


def template(template_id: str) -> dict[str, Any] | None:
    key = str(template_id or "").strip().lower()
    for row in TEMPLATES:
        if row["id"] == key:
            return deepcopy(row)
    return None


def standalone_ids() -> tuple[str, ...]:
    return tuple(row["id"] for row in TEMPLATES if row["standalone"])


def form_codes() -> tuple[str, ...]:
    seen: list[str] = []
    for row in TEMPLATES:
        if row["form"] not in seen:
            seen.append(row["form"])
    return tuple(seen)
