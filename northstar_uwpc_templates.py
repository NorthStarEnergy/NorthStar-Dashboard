"""NorthStar work-protection draft templates.

These sheets cite the 2024 Utility Work Protection Code by form code,
section, and article only. The PC1 application also mirrors the field layout
of the company form workbook supplied for this project. No sheet issues a
permit or operational release.

Applying a template never issues a Work Permit, Supporting Guarantee, tag,
or operational release.
"""
from __future__ import annotations

from copy import deepcopy
from typing import Any

NOTICE = (
    "NorthStar draft sheet. Cites UWPC 2024. "
    "This is not a Work Permit and does not authorize work or operational release."
)


def _rows(*prompts: str) -> list[dict[str, str]]:
    return [{"first": prompt, "second": ""} for prompt in prompts]


def _field(field_id: str, label: str, hint: str = "") -> dict[str, str]:
    return {"id": field_id, "label": label, "hint": hint}


def _template(
    *,
    template_id: str,
    form: str,
    form_revision: str = "",
    title: str,
    kind: str,
    section: str,
    article: str,
    instrument_id: str,
    standalone: bool,
    purpose: str,
    notice: str = NOTICE,
    roles: tuple[str, ...],
    related: tuple[str, ...],
    fields: tuple[dict[str, str], ...],
    isolation: tuple[str, ...],
    sequence: tuple[str, ...],
    verification: tuple[str, ...],
    permission: tuple[str, ...],
    restoration: tuple[str, ...],
) -> dict[str, Any]:
    return {
        "id": template_id,
        "form": form,
        "formRevision": form_revision,
        "title": title,
        "kind": kind,
        "section": section,
        "article": article,
        "instrumentId": instrument_id,
        "standalone": standalone,
        "purpose": purpose,
        "roles": list(roles),
        "related": list(related),
        "notice": notice,
        "fields": list(fields),
        "reviewRows": {
            "isolation": _rows(*isolation),
            "sequence": _rows(*sequence),
            "verification": _rows(*verification),
            "permission": _rows(*permission),
            "restoration": _rows(*restoration),
        },
    }


